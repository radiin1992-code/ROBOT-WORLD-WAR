CREATE TABLE IF NOT EXISTS players (
 telegram_id INTEGER PRIMARY KEY,
 username TEXT NOT NULL DEFAULT '',
 first_name TEXT NOT NULL DEFAULT 'Commander',
 coins INTEGER NOT NULL DEFAULT 250,
 level INTEGER NOT NULL DEFAULT 1,
 wins INTEGER NOT NULL DEFAULT 0,
 losses INTEGER NOT NULL DEFAULT 0,
 selected_robot TEXT NOT NULL DEFAULT 'aegis',
 created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS battles (
 id INTEGER PRIMARY KEY AUTOINCREMENT,
 telegram_id INTEGER NOT NULL,
 robot TEXT NOT NULL,
 result TEXT NOT NULL CHECK(result IN ('win','loss')),
 rounds INTEGER NOT NULL DEFAULT 1,
 created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(telegram_id) REFERENCES players(telegram_id)
);
CREATE INDEX IF NOT EXISTS idx_battles_player ON battles(telegram_id,created_at);